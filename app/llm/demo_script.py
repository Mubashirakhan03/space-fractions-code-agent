"""Scripted responses for the GUI's "Developer: mock mode".

Lets anyone exercise the whole pipeline (plan → implement → verify → report, tools, sandbox, GUI
updates, Run-game button) with zero API cost. The project it writes is a tiny, clearly labelled
MOCK DEMO — it is NOT the Space Fractions game and was not generated by an LLM.
"""

from __future__ import annotations

from app.llm.mock import MockProvider, reply, tool_call

BANNER = "MOCK DEMO — scripted by the developer for pipeline testing, NOT generated by an LLM"

_MAIN = f'''"""{BANNER}"""
import tkinter as tk
from fractions import Fraction

from game.logic import check_answer


def main():
    root = tk.Tk()
    root.title("Mock demo")
    tk.Label(root, text="{BANNER}", fg="red", wraplength=380).pack(padx=12, pady=8)
    tk.Label(root, text="What is 1/2 + 1/4 ?").pack()
    entry = tk.Entry(root)
    entry.pack(pady=4)
    result = tk.Label(root, text="")
    result.pack()

    def submit():
        ok = check_answer(entry.get(), Fraction(3, 4))
        result.config(text="Correct!" if ok else "Try again")

    tk.Button(root, text="Check", command=submit).pack(pady=6)
    root.mainloop()


if __name__ == "__main__":
    main()
'''

_LOGIC = '''from fractions import Fraction


def check_answer(text: str, expected: Fraction) -> bool:
    try:
        return Fraction(text.strip()) == expected
    except (ValueError, ZeroDivisionError):
        return False
'''

_TEST = '''from fractions import Fraction

from game.logic import check_answer


def test_equivalent_forms_accepted():
    assert check_answer("3/4", Fraction(3, 4))
    assert check_answer("6/8", Fraction(3, 4))


def test_bad_input_rejected():
    assert not check_answer("abc", Fraction(1, 2))
    assert not check_answer("1/0", Fraction(1, 2))
'''

_DESIGN = f"""# DESIGN_DECISIONS.md ({BANNER})

| Original element | Desktop equivalent | Reason |
|---|---|---|
| Microservices / REST | in-process Python modules | single-user desktop app |
| PostgreSQL | SQLite | no server needed |
| Kubernetes / Docker | not applicable | runs locally |

## Input issues found
See agent_run/spec.json → input_issues (this mock demo does not analyse them).
"""

FILES = [
    {"path": "main.py", "content": _MAIN},
    {"path": "game/__init__.py", "content": ""},
    {"path": "game/logic.py", "content": _LOGIC},
    {"path": "tests/test_logic.py", "content": _TEST},
    {"path": "README.md", "content": f"# Mock demo\n\n**{BANNER}.**\n\nRun: `python main.py`\n"},
    {"path": "requirements.txt", "content": "# standard library only\npytest\n"},
    {"path": "TRACEABILITY.csv", "content": "requirement,feature,component,file,test\nFR-1,Play game,GameComponent,"
                                            "game/logic.py,tests/test_logic.py\n"},
    {"path": "sql/schema.sql", "content": "CREATE TABLE IF NOT EXISTS scores (id INTEGER PRIMARY KEY, score INT);\n"},
    {"path": "data/questions.json", "content": '[{"prompt": "1/2 + 1/4", "answer": "3/4"}]\n'},
]


def demo_provider() -> MockProvider:
    todos = [{"content": "Write mock demo files", "status": "in_progress"},
             {"content": "Verify with compile + pytest", "status": "pending"}]
    done = [{"content": "Write mock demo files", "status": "completed"},
            {"content": "Verify with compile + pytest", "status": "in_progress"}]
    return MockProvider([
        reply(tool_call("update_todos", "t1", todos=todos),
              tool_call("submit_plan", "p1", design_decisions=_DESIGN, file_tree=[f["path"] for f in FILES],
                        notes=BANNER),
              content="(mock) Planning the demo project."),
        reply(tool_call("write_files", "w1", files=FILES), tool_call("update_todos", "t2", todos=done),
              content="(mock) Writing all files in one batch."),
        reply(tool_call("run_python", "c1", action="compile"), tool_call("run_python", "r1", action="test")),
        reply(tool_call("finish", "f1", summary="Mock demo written and tested.")),
    ])
