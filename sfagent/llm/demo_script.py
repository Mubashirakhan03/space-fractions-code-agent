from dataclasses import dataclass
from fractions import Fraction


@dataclass(frozen=True)
class Question:
    prompt: str
    answer: Fraction


QUESTIONS = [
    Question("1/2 + 1/4 = ?", Fraction(3, 4)),
    Question("Simplify 6/8", Fraction(3, 4)),
    Question("2/3 - 1/6 = ?", Fraction(1, 2)),
]


def check_answer(text: str, expected: Fraction) -> bool:
    """Accept any equivalent form: 3/4, 6/8, 0.75."""
    try:
        return Fraction(text.strip()) == expected
    except (ValueError, ZeroDivisionError):
        return False


def stars_for(score: int, total: int) -> int:
    """0-3 stars by percentage; no correct answers means 0 stars."""
    if total <= 0 or score <= 0:
        return 0
    pct = score / total
    return 3 if pct >= 0.8 else 2 if pct >= 0.5 else 1


ADMIN_PIN = "1234"  # default admin PIN (documented in README.md)


def pin_ok(text: str) -> bool:
    return text.strip() == ADMIN_PIN


def end_message(score: int, total: int) -> str:
    """The message matches the result: no congratulations for a low score."""
    pct = score / total if total else 0
    if pct >= 0.8:
        return "Congratulations!"
    if pct >= 0.5:
        return "Well done!"
    return "Good try! Keep practising"
