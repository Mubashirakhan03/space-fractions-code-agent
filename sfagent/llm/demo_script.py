def big_button(parent, text, command):
    b = tk.Button(parent, text=text, command=command, font=("Segoe UI", 20, "bold"), bg=ACCENT, fg="#1B1B1B",
                  activebackground=ACCENT_HOVER, relief="flat", bd=0, padx=28, pady=10, cursor="hand2")
    b.bind("<Enter>", lambda e: b.config(bg=ACCENT_HOVER))
    b.bind("<Leave>", lambda e: b.config(bg=ACCENT))
    return b


class DemoApp:
    def __init__(self, root):
        self.root = root
        root.title("Space Fractions — MOCK DEMO")
        root.configure(bg=BG)
        root.minsize(1100, 750)
        self._centre(1200, 800)
        root.bind("<F11>", lambda e: root.attributes("-fullscreen", not root.attributes("-fullscreen")))
        root.bind("<Escape>", lambda e: root.attributes("-fullscreen", False))
        self.canvas = tk.Canvas(root, bg=BG, highlightthickness=0)
        self.canvas.place(relx=0, rely=0, relwidth=1, relheight=1)
        self.canvas.bind("<Configure>", lambda e: self._draw_space())
        tk.Label(root, text=BANNER, font=("Segoe UI", 12, "bold"), fg="#FFFFFF", bg="#B42318").pack(fill="x")
        self.panel = tk.Frame(root, bg=PANEL, padx=50, pady=36)
        self.panel.place(relx=0.5, rely=0.52, anchor="center")
        self.screen = ""
        self.intro_jobs = []
        # create_app contract: screens + show()
        self.screens = {{name: self.panel for name in ("intro", "question", "end", "admin_pin", "admin")}}
        self.show_intro()

    def show(self, name):
        {{"intro": self.show_intro, "question": self.start, "end": self.show_end, "admin_pin": self.show_pin,
         "admin": self.show_admin}}[name]()

    def _centre(self, w, h):
        sw, sh = self.root.winfo_screenwidth(), self.root.winfo_screenheight()
        self.root.geometry(f"{{w}}x{{h}}+{{max((sw - w) // 2, 0)}}+{{max((sh - h) // 3, 0)}}")

    def _draw_space(self):
        c = self.canvas
        c.delete("space")
        w, h = max(c.winfo_width(), 1100), max(c.winfo_height(), 750)
        rnd = random.Random(42)
        for _ in range(140):
            x, y, r = rnd.randrange(w), rnd.randrange(h), rnd.choice([1, 1, 2, 3])
            c.create_oval(x - r, y - r, x + r, y + r, fill="#FFFFFF", outline="", tags="space")
        for fx, fy, r, colour in PLANETS:
            x, y = fx * w, fy * h
            c.create_oval(x - r, y - r, x + r, y + r, fill=colour, outline="", tags="space")
        c.tag_lower("space")

    def _clear(self):
        self._stop_intro()
        for child in self.panel.winfo_children():
            child.destroy()

    # --- animated introductory scene: a rocket flies across the sky for 6 s, Skip or auto-advance ---
    INTRO_FRAMES = 180  # 180 x 33 ms = 6 s

    def show_intro(self):
        self._clear()
        self.screen = "intro"
        tk.Label(self.panel, text="Space Fractions", font=("Segoe UI", 40, "bold"), fg=ACCENT, bg=PANEL).pack()
        tk.Label(self.panel, text="Mission briefing: get ready for fraction practice!", font=("Segoe UI", 22),
                 fg=TEXT, bg=PANEL).pack(pady=(6, 18))
        self.skip_btn = big_button(self.panel, "Skip ⏭", self.skip_intro)
        self.skip_btn.pack()
        c = self.canvas
        h = max(c.winfo_height(), 750)
        y = 0.16 * h
        c.create_polygon(0, y - 18, 70, y, 0, y + 18, fill="#E0E7FF", outline="", tags="ship")
        c.create_oval(30, y - 8, 46, y + 8, fill="#4CC9F0", outline="", tags="ship")
        c.create_polygon(0, y - 10, -28, y, 0, y + 10, fill="#FF8C42", outline="", tags="ship")
        self._intro_step(0)

    def _intro_step(self, frame):
        if self.screen != "intro":
            return
        if frame >= self.INTRO_FRAMES:
            self.skip_intro()
            return
        self.canvas.move("ship", 7, -0.2 if frame % 20 < 10 else 0.2)
        self.intro_jobs.append(self.root.after(33, lambda: self._intro_step(frame + 1)))

    def _stop_intro(self):
        for job in self.intro_jobs:
            self.root.after_cancel(job)
        self.intro_jobs = []
        self.canvas.delete("ship")

    def skip_intro(self):
        self._stop_intro()
        self.start()

    # --- admin area behind an in-window PIN ---
    def show_pin(self):
        self._clear()
        self.screen = "admin_pin"
        tk.Label(self.panel, text="Admin — enter PIN", font=("Segoe UI", 32, "bold"), fg=ACCENT, bg=PANEL).pack()
        self.pin_entry = tk.Entry(self.panel, show="*", font=("Segoe UI", 26), width=8, justify="center",
                                  relief="solid", bd=2)
        self.pin_entry.pack(pady=14, ipady=4)
        self.pin_entry.bind("<Return>", lambda e: self.unlock())
        self.pin_entry.focus_set()
        row = tk.Frame(self.panel, bg=PANEL)
        row.pack()
        big_button(row, "Unlock 🔓", self.unlock).pack(side="left", padx=8)
        big_button(row, "Back", self.start).pack(side="left", padx=8)
        self.pin_feedback = tk.Label(self.panel, text="", font=("Segoe UI", 20, "bold"), fg=BAD, bg=PANEL)
        self.pin_feedback.pack(pady=(12, 0))

    def unlock(self):
        if pin_ok(self.pin_entry.get()):
            self.show_admin()
        else:
            self.pin_entry.delete(0, "end")
            self.pin_feedback.config(text="Wrong PIN — try again", fg=BAD)

    def show_admin(self):
        self._clear()
        self.screen = "admin"
        tk.Label(self.panel, text="Admin (mock demo)", font=("Segoe UI", 32, "bold"), fg=ACCENT, bg=PANEL).pack()
        if not hasattr(self, "items"):
            self.items = [f"{{q.prompt}} → {{q.answer}}" for q in QUESTIONS]  # all records, seed data included
        self.item_list = tk.Listbox(self.panel, font=("Segoe UI", 18), width=36, height=5)
        self.item_list.pack(pady=8)
        for item in self.items:
            self.item_list.insert("end", item)
        self.item_entry = tk.Entry(self.panel, font=("Segoe UI", 18), width=36, relief="solid", bd=2)
        self.item_entry.pack(pady=4)
        row = tk.Frame(self.panel, bg=PANEL)
        row.pack(pady=6)
        for text, command in (("Add", self.add_item), ("Edit", self.edit_item), ("Delete", self.delete_item)):
            big_button(row, text, command).pack(side="left", padx=6)
        big_button(self.panel, "Lock and leave", self.start).pack(pady=(10, 0))

    def _selected(self):
        sel = self.item_list.curselection()
        return sel[0] if sel else None

    def add_item(self):
        text = self.item_entry.get().strip()
        if text:
            self.items.append(text)
            self.show_admin()

    def edit_item(self):
        i, text = self._selected(), self.item_entry.get().strip()
        if i is not None and text:
            self.items[i] = text
            self.show_admin()

    def delete_item(self):
        i = self._selected()
        if i is not None:
            del self.items[i]
            self.show_admin()

    def start(self):
        self.index, self.score = 0, 0
        self.show_question()

    def show_question(self):
        self._clear()
        self.screen = "question"
        q = QUESTIONS[self.index]
        tk.Label(self.panel, text="Space Fractions", font=("Segoe UI", 36, "bold"), fg=ACCENT, bg=PANEL).pack()
        self.progress = tk.Label(self.panel, text=f"Question {{self.index + 1}} of {{len(QUESTIONS)}}   ·   "
                                 f"Score {{self.score}}", font=("Segoe UI", 18), fg=TEXT, bg=PANEL)
        self.progress.pack(pady=(4, 18))
        self.question = tk.Label(self.panel, text=q.prompt, font=("Segoe UI", 30, "bold"), fg=TEXT, bg=PANEL)
        self.question.pack(pady=10)
        self.entry = tk.Entry(self.panel, font=("Segoe UI", 28), width=10, justify="center", relief="flat")
        self.entry.pack(pady=12, ipady=6)
        self.entry.bind("<Return>", lambda e: self.submit())
        self.entry.focus_set()
        self.check_btn = big_button(self.panel, "Check ✓", self.submit)
        self.check_btn.pack(pady=10)
        self.feedback = tk.Label(self.panel, text="Type a fraction like 3/4 and press Enter",
                                 font=("Segoe UI", 22, "bold"), fg="#9FB3DF", bg=PANEL)
        self.feedback.pack(pady=(14, 0))

    def submit(self):
        q = QUESTIONS[self.index]
        answer = self.entry.get()
        if not answer.strip():
            return
        if check_answer(answer, q.answer):
            self.score += 1
            self.feedback.config(text="Correct! 🎉", fg=OK)
        else:
            self.feedback.config(text=f"Not quite — the answer is {{q.answer}}", fg=BAD)
        self.entry.delete(0, "end")  # auto-clear for the next question
        self.check_btn.config(state="disabled")
        self.root.after(1200, self.next_question)

    def next_question(self):
        self.index += 1
        if self.index < len(QUESTIONS):
            self.show_question()
        else:
            self.show_end()

    def show_end(self):
        self._clear()
        self.screen = "end"
        total = len(QUESTIONS)
        stars = stars_for(self.score, total)
        self.end_title = tk.Label(self.panel, text=end_message(self.score, total), font=("Segoe UI", 36, "bold"),
                                  fg=ACCENT, bg=PANEL)
        self.end_title.pack()
        tk.Label(self.panel, text="★" * stars + "☆" * (3 - stars), font=("Segoe UI", 56), fg="#FFD60A",
                 bg=PANEL).pack(pady=6)
        tk.Label(self.panel, text=f"You scored {{self.score}} of {{total}} ({{round(100 * self.score / total)}}%)",
                 font=("Segoe UI", 26), fg=TEXT, bg=PANEL).pack(pady=6)
        row = tk.Frame(self.panel, bg=PANEL)
        row.pack(pady=18)
        big_button(row, "Play again", self.start).pack(side="left", padx=10)
        big_button(row, "Admin 🔒", self.show_pin).pack(side="left", padx=10)
        big_button(row, "Quit", self.root.destroy).pack(side="left", padx=10)
        if stars == 3:  # celebrate only a high score
            self._confetti(40)

    def _confetti(self, frames):
        c = self.canvas
        c.delete("confetti")
        if frames <= 0 or self.screen != "end":
            return
        w, h = max(c.winfo_width(), 1100), max(c.winfo_height(), 750)
        rnd = random.Random(frames)
        for _ in range(60):
            x, y = rnd.randrange(w), rnd.randrange(h)
            colour = rnd.choice([ACCENT, OK, BAD, "#4CC9F0", "#F72585"])
            c.create_rectangle(x, y, x + 8, y + 14, fill=colour, outline="", tags="confetti")
        self.root.after(120, lambda: self._confetti(frames - 1))


def maximize(root):
    try:
        root.state("zoomed")
    except tk.TclError:
        root.attributes("-zoomed", True)


def create_app(root):
    return DemoApp(root)
