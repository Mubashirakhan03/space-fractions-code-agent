def make_root():
    """Tk() can fail transiently on Windows; retry before treating it as 'no display'."""
    error = None
    for _ in range(3):
        try:
            return tk.Tk()
        except tk.TclError as exc:
            error = exc
            time.sleep(0.3)
    pytest.skip(f"no display: {error}")


def cancel_pending(root):
    for after_id in root.tk.call("after", "info"):
        root.after_cancel(after_id)


@pytest.fixture(scope="session")
def root():
    """ONE Tk root for the whole session: re-creating Tk after destroy() can crash on Windows."""
    r = make_root()
    r.withdraw()
    yield r
    cancel_pending(r)
    r.destroy()


def pump(root, seconds):
    end = time.time() + seconds
    while time.time() < end:
        root.update()
        time.sleep(0.02)


@pytest.fixture
def fresh(root):
    yield create_app(root)
    cancel_pending(root)
    for child in root.winfo_children():
        child.destroy()


